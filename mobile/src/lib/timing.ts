// Тайминги смены кадра погоды. Лежат отдельно, потому что нужны с двух сторон:
// карта ими перелистывает слой, таймлайн — задаёт по ним темп проигрывания.
// Если развести константы по компонентам, они рано или поздно разъедутся.

// Фора новому кадру на загрузку тайлов, прежде чем его проявлять. Снимок
// EUMETSAT отдаётся за 0.4–0.9 с, но тайлы идут параллельно и в кэш.
export const CLOUD_PRELOAD_MS = 500;

// Проявление поверх предыдущего кадра.
export const CLOUD_FADE_MS = 400;

// Полная смена кадра. Проигрывание не должно идти быстрее: иначе следующий
// кроссфейд начнётся поверх незакончившегося и картинка задёргается.
export const CLOUD_SETTLE_MS = CLOUD_PRELOAD_MS + CLOUD_FADE_MS;
